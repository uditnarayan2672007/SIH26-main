// Enhance real mines data with synthetic fields for compatibility
const enhanceRealMinesData = (mines: any[]): MineSite[] => {
  if (!mines || mines.length === 0) return [];
  return mines.map((mine, idx) => ({
    id: mine.id,
    name: mine.name,
    code: mine.code,
    subsidiary: mine.subsidiary,
    state: mine.state,
    district: mine.district,
    type: mine.type,
    coordinates: mine.coordinates,
    productionCapacityMTPA: mine.productionCapacityMTPA || 0,
    currentProductionMT: mine.currentProductionMT || 0,
    activeWorkforce: Math.floor(Math.random() * 2000 + 500),
    complianceScore: Math.floor(Math.random() * 20 + 75),
    safetyRating: ['A+', 'A', 'B', 'C'][Math.floor(Math.random() * 4)] as 'A+' | 'A' | 'B' | 'C',
    dgmsZone: `Zone-${idx % 5}`,
    projectOfficer: `Officer ${idx}`,
    lastDgmsInspectionDate: new Date(Date.now() - Math.random() * 30 * 24 * 60 * 60 * 1000)
      .toISOString()
      .split('T')[0],
    activeAlertsCount: Math.floor(Math.random() * 5),
  }));
};

